# Stem rewrites inside CARRIED lessons (R10b near-dup fixes). Keyed by
# lesson title; old stem → new stem. Applied after the build, idempotent.
STEM_FIXES = {
    "سورة الناس": {
        "أكمل: قل أعوذ برب ...":
            "أكمل الآية الأولى من سورة الناس: قل أعوذ برب ...",
    },
}


def _load(stem):
    with (CURRICULUM_DIR / f"{stem}.json").open(encoding="utf-8") as f:
        return json.load(f)


def _save(stem, data):
    data["totalLessons"] = len(data["lessons"])
    with (CURRICULUM_DIR / f"{stem}.json").open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")


def main() -> None:
    old_p1 = _load("re1_p1")
    old_p2 = _load("re1_p2")
    bank = {"p1": {l["title"]: l for l in old_p1["lessons"]},
            "p2": {l["title"]: l for l in old_p2["lessons"]}}

    def build(plan):
        lessons = []
        for idx, (title, source) in enumerate(plan, start=1):
            if isinstance(source, dict):
                lesson = dict(source)
            else:
                side, old_title = source
                lesson = bank[side].get(old_title)
                if lesson is None:
                    # Already-rebuilt files: the lesson lives under its NEW
                    # title, possibly on the other side (cross-file moves).
                    lesson = bank["p1"].get(title) or bank["p2"].get(title)
                if lesson is None:
                    raise SystemExit(f"carry-over source not found: {source} → {title}")
                lesson = dict(lesson)
                lesson["title"] = title
            lesson["orderIndex"] = idx
            lessons.append(lesson)
        return lessons

    p1_lessons = build(P1_PLAN)
    p2_lessons = build(P2_PLAN)

    for lessons in (p1_lessons, p2_lessons):
        for lesson in lessons:
            fixes = STEM_FIXES.get(lesson["title"])
            if not fixes:
                continue
            for qq in lesson["questions"]:
                new_text = fixes.get(qq["questionText"])
                if new_text:
                    qq["questionText"] = new_text

    _save("re1_p1", {**old_p1, "lessons": p1_lessons})
    _save("re1_p2", {**old_p2, "lessons": p2_lessons})
    for stem, ls in (("re1_p1", p1_lessons), ("re1_p2", p2_lessons)):
        print(f"{stem}: {len(ls)} lessons, "
              f"{sum(len(l['questions']) for l in ls)} questions")


if __name__ == "__main__":
    main()
