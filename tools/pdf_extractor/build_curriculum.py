def save_curriculum(data, filename):
    data["totalLessons"] = len(data["lessons"])
    for lesson in data["lessons"]:
        lesson.pop("startPage", None)
        lesson["imageUrls"] = []

    filepath = OUTPUT_DIR / filename
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    total_q = sum(len(l["questions"]) for l in data["lessons"])
    print(f"  {filename}: {data['totalLessons']} lessons, {total_q} questions")


